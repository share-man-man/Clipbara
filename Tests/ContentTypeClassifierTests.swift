import AppKit
import XCTest

@MainActor
final class ContentTypeClassifierTests: XCTestCase {
    /// Private settings domain for this test's capture preferences.
    private let suiteName = "ClipbaraTests.Privacy.\(UUID().uuidString)"
    private var defaults: UserDefaults!
    private var pasteboard: NSPasteboard!
    /// The monitor uses one classifier even when the user changes a preference.
    private let classifier = ContentTypeClassifier()

    override func setUp() async throws {
        defaults = try XCTUnwrap(UserDefaults(suiteName: suiteName))
        pasteboard = .withUniqueName()
    }

    override func tearDown() async throws {
        defaults.removePersistentDomain(forName: suiteName)
        pasteboard.releaseGlobally()
    }

    /// Classifies plain text from a private clipboard with the specified markers.
    /// - Parameter markers: Content-type markers supplied by the copying application.
    private func captures(_ markers: NSPasteboard.PasteboardType...) -> Bool {
        // Publish the marker types alongside the text, as a third-party application would.
        let item = NSPasteboardItem()
        item.setString("example", forType: .string)
        for marker in markers {
            item.setData(Data(), forType: marker)
        }
        pasteboard.clearContents()
        XCTAssertTrue(pasteboard.writeObjects([item]))
        return classifier.classify(pasteboard, defaults: defaults)?.textContent == "example"
    }

    func testDefaultIgnoresConfidentialAndTemporaryContent() {
        XCTAssertTrue(captures())
        XCTAssertFalse(captures(.concealedContent))
        XCTAssertFalse(captures(.transientContent))
        XCTAssertFalse(captures(.autoGeneratedContent))
    }

    func testPrivacyTogglesTakeEffectIndependentlyOnTheNextCopy() {
        defaults.set(false, forKey: ContentTypeClassifier.ignoresConfidentialDefaultsKey)
        XCTAssertTrue(captures(.concealedContent))
        XCTAssertFalse(captures(.concealedContent, .transientContent))
        XCTAssertFalse(captures(.autoGeneratedContent))

        defaults.set(false, forKey: ContentTypeClassifier.ignoresTransientDefaultsKey)
        XCTAssertTrue(captures(.concealedContent, .transientContent, .autoGeneratedContent))

        defaults.set(true, forKey: ContentTypeClassifier.ignoresConfidentialDefaultsKey)
        XCTAssertFalse(captures(.concealedContent, .transientContent))
        XCTAssertTrue(captures(.transientContent))
        XCTAssertTrue(captures(.autoGeneratedContent))
    }
}
